"""Build the MITRE ATT&CK coverage report from compiled rules.

Run with:  python -m pipeline.coverage
Writes docs/attck-coverage.md (committed, so reviewers see it on GitHub).
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from typing import Any

from pipeline.common import (
    COMPILED_DIR,
    DOCS_DIR,
    LEVEL_RANK,
    TACTIC_ORDER,
    ensure_dir,
)

# Techniques a SOC hiring manager expects a junior analyst to know about.
# Anything here that is not covered shows up as a documented gap, which is a
# more honest (and more useful) artifact than claiming full coverage.
PRIORITY_TECHNIQUES = {
    "T1059.001": "PowerShell",
    "T1059.003": "Windows Command Shell",
    "T1059.004": "Unix Shell",
    "T1003.001": "LSASS Memory",
    "T1055": "Process Injection",
    "T1053.005": "Scheduled Task",
    "T1053.003": "Cron",
    "T1543.003": "Windows Service",
    "T1547.001": "Registry Run Keys",
    "T1110.001": "Password Guessing",
    "T1110.003": "Password Spraying",
    "T1078": "Valid Accounts",
    "T1071.001": "Web Protocols",
    "T1105": "Ingress Tool Transfer",
    "T1562.001": "Disable or Modify Tools",
    "T1505.003": "Web Shell",
    "T1136.001": "Local Account",
    "T1021.004": "SSH",
    "T1041": "Exfiltration Over C2 Channel",
    "T1486": "Data Encrypted for Impact",
}

TACTIC_LABEL = {
    "reconnaissance": "Reconnaissance",
    "resource_development": "Resource Development",
    "initial_access": "Initial Access",
    "execution": "Execution",
    "persistence": "Persistence",
    "privilege_escalation": "Privilege Escalation",
    "defense_evasion": "Defense Evasion",
    "credential_access": "Credential Access",
    "discovery": "Discovery",
    "lateral_movement": "Lateral Movement",
    "collection": "Collection",
    "command_and_control": "Command and Control",
    "exfiltration": "Exfiltration",
    "impact": "Impact",
}


def _load_compiled() -> list[dict[str, Any]]:
    path = COMPILED_DIR / "rules.json"
    if not path.exists():
        raise SystemExit("rules/compiled/rules.json missing. Run: python -m pipeline.compile")
    return json.loads(path.read_text(encoding="utf-8"))


def build_markdown(compiled: list[dict[str, Any]]) -> str:
    by_tactic: dict[str, list[dict[str, Any]]] = defaultdict(list)
    technique_rows: list[tuple[str, str, str, str, str]] = []
    covered: set[str] = set()

    for rule in compiled:
        for tactic in rule.get("tactics") or ["uncategorised"]:
            by_tactic[tactic].append(rule)
        for technique in rule.get("techniques") or []:
            covered.add(technique)
            for tactic in rule.get("tactics") or ["uncategorised"]:
                technique_rows.append(
                    (technique, TACTIC_LABEL.get(tactic, tactic), rule["level"], rule["title"], rule["logsource"].get("product", "-"))
                )

    techniques = {row[0] for row in technique_rows}
    tactics_covered = [t for t in TACTIC_ORDER if t in by_tactic]

    lines: list[str] = []
    lines.append("# MITRE ATT&CK Coverage")
    lines.append("")
    lines.append("> Generated by `python -m pipeline.coverage`. Do not edit by hand.")
    lines.append("> Source of truth: `rules/sigma/*.yml` (Sigma), compiled to EQL in `rules/compiled/rules.json`.")
    lines.append("")
    lines.append(
        f"**{len(compiled)} detections** covering **{len(techniques)} techniques** "
        f"across **{len(tactics_covered)} tactics**."
    )
    lines.append("")

    lines.append("## Coverage by tactic")
    lines.append("")
    lines.append("| Tactic | Techniques | Detections |")
    lines.append("|---|---|---|")
    for tactic in tactics_covered:
        rules = by_tactic[tactic]
        tactic_techniques = sorted({t for rule in rules for t in rule.get("techniques") or []})
        lines.append(
            f"| {TACTIC_LABEL.get(tactic, tactic)} | {', '.join(tactic_techniques) or '-'} | {len(rules)} |"
        )
    lines.append("")

    lines.append("## Detection detail")
    lines.append("")
    lines.append("| Technique | Tactic | Level | Detection | Source |")
    lines.append("|---|---|---|---|---|")
    for technique, tactic, level, title, source in sorted(
        technique_rows, key=lambda row: (TACTIC_ORDER.index(next((t for t in TACTIC_ORDER if TACTIC_LABEL[t] == row[1]), TACTIC_ORDER[0])), row[0])
    ):
        lines.append(f"| {technique} | {tactic} | {level} | {title} | {source} |")
    lines.append("")

    gaps = [f"{technique} ({name})" for technique, name in PRIORITY_TECHNIQUES.items() if technique not in covered]
    lines.append("## Known gaps")
    lines.append("")
    if gaps:
        lines.append("Priority techniques not yet covered. These are the next rules to write:")
        lines.append("")
        for gap in gaps:
            lines.append(f"- {gap}")
    else:
        lines.append("All priority techniques are covered.")
    lines.append("")

    return "\n".join(lines)


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Generate the ATT&CK coverage report")
    parser.add_argument("--check", action="store_true", help="fail if docs/attck-coverage.md is stale (for CI)")
    args = parser.parse_args()

    compiled = _load_compiled()
    markdown = build_markdown(compiled)
    target = DOCS_DIR / "attck-coverage.md"

    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != markdown:
            print("docs/attck-coverage.md is stale. Run: python -m pipeline.coverage")
            return 1
        print("ATT&CK coverage report is up to date.")
        return 0

    ensure_dir(DOCS_DIR)
    target.write_text(markdown, encoding="utf-8")
    print(f"Wrote docs/attck-coverage.md ({len(compiled)} rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
